/** Contract v1.0 domain ports. Strictly mock-only; no live network calls. */
import { parseQuestV1, type QuestV1 } from './contract-v1';
import { questFixtureV1 } from './fixtures-v1';
import type { LearningPath } from './types';

export interface SubmitAssessmentRequestV1 {
  quest_version_id: string;
  idempotency_key: string; // uuid
  answers: Array<{ item_id: string; value: string }>;
}
export interface SubmitAssessmentDataV1 {
  attempt_id: string; // uuid, generated by server
  status: 'scored';
  score: number; // integer 0..100
  feedback: Array<{ item_id?: string; correct?: boolean; message?: string }>;
  next_path: LearningPath;
}
export type ApiSuccessV1<T> = { ok: true; data: T; request_id: string };
export type ApiErrorCodeV1 = 'VALIDATION_ERROR' | 'UNAUTHORIZED' | 'FORBIDDEN' | 'NOT_FOUND'
  | 'RATE_LIMITED' | 'AI_UNAVAILABLE' | 'CONFLICT' | 'INTERNAL_ERROR';
export interface ApiErrorV1 {
  ok: false;
  error: { code: ApiErrorCodeV1; message: string };
  request_id: string;
}
export interface QuestPortV1 {
  /** GET response schema is still UNDEFINED in OpenAPI; this is just a domain port. */
  getPublishedQuest(questId: string): Promise<QuestV1>;
}
export interface AssessmentPortV1 {
  submitAnswers(input: SubmitAssessmentRequestV1): Promise<ApiSuccessV1<SubmitAssessmentDataV1>>;
}

export class MockQuestRepositoryV1 implements QuestPortV1 {
  async getPublishedQuest(questId: string): Promise<QuestV1> {
    if (questId !== questFixtureV1.quest_id) throw new Error('QUEST_NOT_FOUND (mock)');
    return parseQuestV1(questFixtureV1);
  }
}

const uuidPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** DEMO ONLY. Does not grade answers, authenticate students, or simulate authoritative scoring.
 * Do not wire into a public real-user flow. In live application use PIC B's authenticated endpoint.
 */
export class MockAssessmentRepositoryV1 implements AssessmentPortV1 {
  readonly isMock = true as const;
  constructor(private readonly path: LearningPath = 'need_more_evidence') {}

  async submitAnswers(input: SubmitAssessmentRequestV1): Promise<ApiSuccessV1<SubmitAssessmentDataV1>> {
    if (!input.quest_version_id || !uuidPattern.test(input.idempotency_key) ||
        !Array.isArray(input.answers) || input.answers.length === 0 ||
        !input.answers.every(a => !!a && typeof a.item_id === 'string' && a.item_id.length > 0 && typeof a.value === 'string')) {
      throw new Error('VALIDATION_ERROR (mock): request tidak sesuai kontrak submit v1');
    }
    return {
      ok: true,
      request_id: 'req-demo-only',
      data: {
        attempt_id: '00000000-0000-4000-8000-000000000001',
        status: 'scored',
        score: 0, // FAKE: not an actual student score; no private answer keys are available.
        feedback: input.answers.map(a => ({
          item_id: a.item_id,
          message: 'Mode mock: nilai ini BUKAN hasil assessment resmi.'
        })),
        next_path: this.path
      }
    };
  }
}
